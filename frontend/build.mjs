import {readFile} from 'node:fs/promises';
import {build} from 'esbuild';

const dependencies = ['react', 'react-dom', 'scheduler'];
const notices = await Promise.all(dependencies.map(async name => {
  const license = await readFile(new URL(`../node_modules/${name}/LICENSE`, import.meta.url), 'utf8');
  return `/* ${name}\n${license.replace(/\r\n/g, '\n').trim()}\n*/`;
}));

await build({
  entryPoints: ['frontend/workspace.jsx'],
  outfile: 'issue_list_bundle.js',
  bundle: true,
  minify: true,
  target: 'es2020',
  define: {'process.env.NODE_ENV': '"production"'},
  banner: {js: '// Generated by npm run build:ui. Edit frontend/ instead.\n' + notices.join('\n')},
});
